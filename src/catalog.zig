pub fn keyboardSample(profile: usize, keycode: u16, pressed: bool) ?usize {
    const prefix = keyboards[if (profile < keyboards.len) profile else 0].prefix;
    const special: []const u8 = if (!pressed) "_release.wav" else switch (keycode) {
        49 => "_space.wav",
        36, 76 => "_enter.wav",
        51, 117 => "_delete.wav",
        else => "",
    };
    var keys: [8]usize = undefined;
    var count: usize = 0;
    for (files, 0..) |file, index| {
        if (!std.mem.startsWith(u8, file, prefix)) continue;
        const role = file[prefix.len..];
        if (std.mem.eql(u8, role, special)) return index;
        if (std.mem.startsWith(u8, role, "_key") or std.mem.eql(u8, role, ".wav")) {
            keys[count] = index;
            count += 1;
        }
    }
    return if (pressed and count > 0) keys[keycode % count] else null;
}

pub fn mouseSample(profile: usize, pressed: bool) ?usize {
    if (profile == 0 or profile > 15) return null;
    var buffer: [32]u8 = undefined;
    const suffix: u8 = if (pressed) 1 else 2;
    const name = if (profile == 15)
        std.fmt.bufPrint(&buffer, "mouse_c_{d}.wav", .{suffix}) catch unreachable
    else
        std.fmt.bufPrint(&buffer, "mouse_{d}_{d}.wav", .{ profile, suffix }) catch unreachable;
    for (files, 0..) |file, index| if (std.mem.eql(u8, file, name)) return index;
    return null;
}

test "every WAV is reachable and original routing stays stable" {
    try std.testing.expectEqual(240, files.len);
    var used = @as([files.len]bool, @splat(false));
    for (0..40) |profile| for (0..128) |key| {
        for ([_]bool{ false, true }) |pressed| if (keyboardSample(profile, @intCast(key), pressed)) |index| {
            used[index] = true;
        };
    };
    for (0..16) |profile| for ([_]bool{ false, true }) |pressed| {
        if (mouseSample(profile, pressed)) |index| used[index] = true;
    };
    for (used) |reachable| try std.testing.expect(reachable);
    for (0..3) |profile| {
        for ([_]u16{ 0, 8, 36, 51 }) |key| {
            const index = keyboardSample(profile, key, true).?;
            const role = files[index][keyboards[profile].prefix.len..];
            try std.testing.expectEqualStrings(switch (key) {
                36 => "_key5.wav",
                51 => "_key4.wav",
                else => "_key1.wav",
            }, role);
        }
        try std.testing.expect(keyboardSample(profile, 0, false) == null);
    }
    try std.testing.expectEqualStrings("t_bell_release.wav", files[keyboardSample(31, 0, false).?]);
    try std.testing.expectEqualStrings("mouse_c_2.wav", files[mouseSample(15, false).?]);
    try std.testing.expect(mouseSample(0, true) == null);
    try std.testing.expectEqual(keyboardSample(0, 0, true), keyboardSample(255, 0, true));
}
